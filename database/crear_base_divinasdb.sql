CREATE TABLE tienda
(
    id_tienda      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nombre_tienda  VARCHAR(100) NOT NULL,
    direccion      VARCHAR(150) NOT NULL,
    telefono       VARCHAR(9)   NOT NULL,
    usuario_admin  VARCHAR(30)  NOT NULL,
    password_admin VARCHAR(60)  NOT NULL,
    estado         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_tienda PRIMARY KEY (id_tienda),
    CONSTRAINT uk_tienda_nombre UNIQUE (nombre_tienda),
    CONSTRAINT uk_tienda_usuario_admin UNIQUE (usuario_admin),
    CONSTRAINT ck_tienda_telefono CHECK (telefono ~ '^[0-9]{9}$')
);

CREATE TABLE cliente
(
    id_cliente         INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_tienda          INTEGER        NOT NULL,
    nombre_cliente     VARCHAR(100)   NOT NULL,
    tipo_tasa          VARCHAR(10)    NOT NULL,
    tasa_interes       NUMERIC(10, 4) NOT NULL,
    capitalizacion     VARCHAR(15)    NULL,
    moneda             VARCHAR(10)    NOT NULL DEFAULT 'Soles',
    limite_max_credito NUMERIC(12, 2) NOT NULL,
    max_meses_credito  INTEGER        NOT NULL,
    fecha_corte        INTEGER        NOT NULL,
    fecha_pago         INTEGER        NOT NULL,
    usuario_cliente    VARCHAR(30)    NOT NULL,
    password_cliente   VARCHAR(60)    NOT NULL,
    estado             BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT uk_cliente_tienda_usuario UNIQUE (id_tienda, usuario_cliente),
    CONSTRAINT ck_cliente_tipo_tasa CHECK (tipo_tasa IN ('Nominal', 'Efectiva')),
    CONSTRAINT ck_cliente_tasa CHECK (tasa_interes > 0 AND tasa_interes <= 200),
    CONSTRAINT ck_cliente_capitalizacion CHECK (capitalizacion IS NULL OR capitalizacion IN
        ('Diaria', 'Mensual', 'Bimestral', 'Trimestral', 'Semestral', 'Anual')),
    CONSTRAINT ck_cliente_moneda CHECK (moneda = 'Soles'),
    CONSTRAINT ck_cliente_limite CHECK (limite_max_credito > 0),
    CONSTRAINT ck_cliente_max_meses CHECK (max_meses_credito >= 1),
    CONSTRAINT ck_cliente_fecha_corte CHECK (fecha_corte BETWEEN 1 AND 31),
    CONSTRAINT ck_cliente_fecha_pago CHECK (fecha_pago BETWEEN 1 AND 31)
);

CREATE TABLE producto_servicio
(
    id_producto_servicio INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_tienda            INTEGER        NOT NULL,
    imagen               VARCHAR(255)   NULL,
    proveedor            VARCHAR(80)    NULL,
    marca                VARCHAR(50)    NULL,
    descripcion          VARCHAR(150)   NOT NULL,
    unidad_medida        VARCHAR(20)    NOT NULL,
    precio_contado       NUMERIC(12, 2) NOT NULL,
    forma_venta          VARCHAR(15)    NOT NULL DEFAULT 'En meses',
    estado               BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_producto_servicio PRIMARY KEY (id_producto_servicio),
    CONSTRAINT ck_producto_precio_contado CHECK (precio_contado > 0),
    CONSTRAINT ck_producto_forma_venta CHECK (forma_venta IN ('Al contado', 'En meses'))
);

CREATE TABLE compra
(
    id_compra            INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_cliente           INTEGER        NOT NULL,
    id_producto_servicio INTEGER        NOT NULL,
    fecha_compra         DATE           NOT NULL,
    monto                NUMERIC(12, 2) NOT NULL,
    forma_pago           VARCHAR(15)    NOT NULL,
    num_meses            INTEGER        NOT NULL DEFAULT 1,
    CONSTRAINT pk_compra PRIMARY KEY (id_compra),
    CONSTRAINT ck_compra_monto CHECK (monto > 0),
    CONSTRAINT ck_compra_forma_pago CHECK (forma_pago IN ('Unico pago', 'En meses')),
    CONSTRAINT ck_compra_num_meses CHECK (num_meses >= 1)
);

CREATE TABLE cuota
(
    id_cuota          INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_compra         INTEGER        NOT NULL,
    numero_cuota      INTEGER        NOT NULL,
    fecha_vencimiento DATE           NOT NULL,
    monto_cuota       NUMERIC(12, 2) NOT NULL,
    estado            VARCHAR(10)    NOT NULL DEFAULT 'Pendiente',
    fecha_pago_real   DATE           NULL,
    CONSTRAINT pk_cuota PRIMARY KEY (id_cuota),
    CONSTRAINT uk_cuota_compra_numero UNIQUE (id_compra, numero_cuota),
    CONSTRAINT ck_cuota_numero CHECK (numero_cuota >= 1),
    CONSTRAINT ck_cuota_monto CHECK (monto_cuota > 0),
    CONSTRAINT ck_cuota_estado CHECK (estado IN ('Pendiente', 'Pagado'))
);

